await mongoose.connect(config.mongoUri);
const dir = path.join(config.uploadDir, "audio");
fs.mkdirSync(dir, { recursive: true });

let artist = await User.findOne({ username: "SoundBox.Demo" });
if (!artist) artist = await User.create({ email: "demo-artist@soundbox.local", username: "SoundBox.Demo", password: await bcrypt.hash(crypto.randomBytes(24).toString("hex"), 10), bio: "Procedurally generated demo tracks released under CC0.", privacy: { showActivity: false, showPlaylists: true } });

let added = 0;
for (const [name, genre, scale, root, wave, tempo, pad, description] of TRACKS) {
  if (await Song.exists({ name, artist: artist._id })) continue;
  const file = `demo-${name.toLowerCase().replace(/\W+/g, "-")}.wav`;
  fs.writeFileSync(path.join(dir, file), wav(synth({ seconds: 40, scale, root, wave, tempo, pad })));
  await Song.create({ name, genre, description, artist: artist._id, track: `/media/audio/${file}`, duration: 40, thumbnail: "", license: "CC0 (generated by SoundBox seed script)", plays: 0 });
  added++;
}
console.log(`[seed] ${added} new demo tracks (${TRACKS.length} total) in ${mongoose.connection.name}`);
await mongoose.disconnect();

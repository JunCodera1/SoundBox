const RATE = 22050;
const note = (n) => 440 * 2 ** ((n - 69) / 12);

function synth({ seconds, scale, root, wave, tempo, pad }) {
  const n = RATE * seconds, out = new Int16Array(n), step = Math.floor((RATE * 60) / tempo / 2);
  const seq = Array.from({ length: Math.ceil(n / step) }, (_, i) => root + scale[(i * 3 + (i >> 2)) % scale.length]);
  for (let i = 0; i < n; i++) {
    const k = Math.floor(i / step), t = (i % step) / step, f = note(seq[k]);
    const env = Math.min(1, t * 20) * Math.exp(-t * 2.2);
    const ph = (2 * Math.PI * f * i) / RATE;
    let v = wave === "sine" ? Math.sin(ph) : wave === "tri" ? (2 / Math.PI) * Math.asin(Math.sin(ph)) : Math.sign(Math.sin(ph)) * 0.5 + 0.5 * Math.sin(ph);
    v *= env * 0.5;
    if (pad) v += 0.18 * Math.sin((2 * Math.PI * note(root - 12) * i) / RATE);
    const fade = Math.min(1, i / 2000, (n - i) / 4000);
    out[i] = Math.round(Math.max(-1, Math.min(1, v * fade)) * 32000);
  }
  return out;
}
function wav(samples) {
  const buf = Buffer.alloc(44 + samples.length * 2);
  buf.write("RIFF", 0); buf.writeUInt32LE(36 + samples.length * 2, 4); buf.write("WAVEfmt ", 8);
  buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22); buf.writeUInt32LE(RATE, 24);
  buf.writeUInt32LE(RATE * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34); buf.write("data", 36); buf.writeUInt32LE(samples.length * 2, 40);
  Buffer.from(samples.buffer).copy(buf, 44);
  return buf;
}

